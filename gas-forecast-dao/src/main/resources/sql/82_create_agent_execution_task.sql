use gas_data;

-- 用户通过智能体、MCP或管理后台发起的一次完整业务目标。
-- 一个任务可以只训练、只预测，也可以先训练再预测；批次重试不得覆盖这里保存的历史关联。
create table if not exists agent_execution_task_tb (
    id bigint unsigned not null auto_increment comment '主键',
    task_no varchar(64) not null comment '统一任务编号',
    parent_task_no varchar(64) default null comment '批量任务或父任务编号，单任务为空',
    conversation_no varchar(64) default null comment '来源会话编号',
    task_type varchar(32) not null comment 'TRAIN/FORECAST/TRAIN_AND_FORECAST',
    trigger_source varchar(32) not null comment 'MCP/AI/MANUAL/SCHEDULE/DATA_EVENT',
    agent_code varchar(64) not null comment 'short-term/monthly-sales/winter-supply',
    scope_type varchar(32) not null comment 'CUSTOMER/REGION/REGION_INDUSTRY',
    region_code varchar(64) default null,
    region_name varchar(128) default null,
    industry_code varchar(64) default null,
    industry_name varchar(128) default null,
    customer_code varchar(64) default null,
    customer_name varchar(128) default null,
    status varchar(32) not null comment 'WAITING/EXECUTING/WAITING_CONFIRMATION/SUCCESS/PARTIAL_SUCCESS/FAILED/CANCELLED',
    current_stage varchar(64) default null comment 'AGENT_PREPARE/TRAINING/FORECASTING/COMPLETED',
    current_step_code varchar(64) default null comment '当前智能体或业务步骤编码',
    progress_percent decimal(5,2) not null default 0 comment '总体进度0到100',
    task_attempt_no int not null default 1 comment '任务级执行次数，任务重试时加1',
    latest_train_batch_no varchar(64) default null comment '当前任务最新训练批次号',
    latest_forecast_batch_no varchar(64) default null comment '当前任务最新预测批次号',
    idempotency_key varchar(128) default null comment '调用幂等键',
    request_json longtext default null comment '用户确认后的标准化任务参数',
    checkpoint_json longtext default null comment '任务级恢复检查点',
    result_json longtext default null comment '最终结果摘要',
    error_code varchar(64) default null,
    error_message text default null,
    retryable tinyint not null default 1 comment '失败后是否允许任务级重试',
    created_by varchar(64) not null,
    created_by_name varchar(128) default null,
    created_at datetime not null default current_timestamp,
    started_at datetime default null,
    finished_at datetime default null,
    updated_at datetime not null default current_timestamp on update current_timestamp,
    primary key (id),
    unique key uk_agent_task_no (task_no),
    unique key uk_agent_task_idempotency (created_by, trigger_source, idempotency_key),
    key idx_agent_task_owner (created_by, status, updated_at),
    key idx_agent_task_conversation (conversation_no, updated_at),
    key idx_agent_task_parent (parent_task_no, status),
    key idx_agent_task_train_batch (latest_train_batch_no),
    key idx_agent_task_forecast_batch (latest_forecast_batch_no)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='智能体统一执行任务';

-- 记录智能体对一个任务执行到哪里。这里只记录可审计动作和高层业务阶段，
-- 训练内部LOAD_DATA、DYNAMIC_FEATURE等详细步骤继续使用model_train_execution_step_tb。
create table if not exists agent_execution_step_tb (
    id bigint unsigned not null auto_increment comment '主键',
    task_no varchar(64) not null comment '统一任务编号',
    task_attempt_no int not null comment '所属任务级执行次数',
    parent_step_id bigint unsigned default null comment '父步骤ID',
    step_level int not null default 1 comment '步骤层级',
    step_category varchar(32) not null comment 'AGENT_ACTION/BUSINESS_STAGE',
    step_code varchar(64) not null comment '步骤编码',
    step_name varchar(128) not null comment '步骤名称',
    step_order int not null comment '步骤顺序',
    status varchar(32) not null comment 'WAITING/RUNNING/SUCCESS/FAILED/SKIPPED/CANCELLED',
    retryable tinyint not null default 1,
    business_ref_type varchar(32) default null comment 'TRAIN_BATCH/FORECAST_BATCH/NONE',
    business_ref_no varchar(64) default null comment '关联训练或预测批次号',
    input_summary text default null comment '工具参数或业务输入摘要，不保存大模型思维链',
    output_summary longtext default null comment '工具结果或步骤产出摘要',
    checkpoint_json longtext default null comment '该步骤成功后的恢复检查点',
    error_code varchar(64) default null,
    error_message text default null,
    started_at datetime default null,
    finished_at datetime default null,
    duration_ms bigint default null,
    created_at datetime not null default current_timestamp,
    updated_at datetime not null default current_timestamp on update current_timestamp,
    primary key (id),
    unique key uk_agent_task_step_attempt (task_no, task_attempt_no, step_code),
    key idx_agent_task_step_order (task_no, task_attempt_no, step_order),
    key idx_agent_task_step_parent (parent_step_id, step_order),
    key idx_agent_task_step_business_ref (business_ref_type, business_ref_no),
    key idx_agent_task_step_status (status, updated_at)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='智能体任务执行步骤';

-- 保存任务与每一次真实训练/预测批次的不可变关联。
-- 任务重试：task_attempt_no增加并写入新的batch_no和previous_batch_no。
-- 后台人工复用失败批次重试：batch_no可保持不变，但batch_attempt_no增加，retry_mode=REUSE_BATCH。
create table if not exists agent_execution_batch_tb (
    id bigint unsigned not null auto_increment comment '主键',
    task_no varchar(64) not null comment '统一任务编号',
    task_attempt_no int not null comment '任务级执行次数',
    stage varchar(32) not null comment 'TRAINING/FORECASTING',
    batch_type varchar(16) not null comment 'TRAIN/FORECAST',
    batch_no varchar(64) not null comment '训练batch_no或预测forecast_batch_no',
    batch_attempt_no int not null default 1 comment '同一批次内部第几次执行',
    previous_batch_no varchar(64) default null comment '创建新批次重试时关联上一个失败批次',
    retry_mode varchar(32) not null default 'NEW_BATCH' comment 'NEW_BATCH/REUSE_BATCH/FIRST_RUN',
    trigger_source varchar(32) not null comment 'TASK_RETRY/ADMIN_RETRY/AUTO_RETRY/FIRST_RUN',
    status varchar(32) not null comment 'WAITING/RUNNING/SUCCESS/FAILED/CANCELLED',
    error_message text default null,
    created_by varchar(64) not null,
    created_by_name varchar(128) default null,
    created_at datetime not null default current_timestamp,
    started_at datetime default null,
    finished_at datetime default null,
    updated_at datetime not null default current_timestamp on update current_timestamp,
    primary key (id),
    unique key uk_agent_task_batch_attempt (task_no, task_attempt_no, stage, batch_no, batch_attempt_no),
    key idx_agent_execution_batch_no (batch_type, batch_no),
    key idx_agent_execution_previous_batch (batch_type, previous_batch_no),
    key idx_agent_execution_task_stage (task_no, stage, status),
    key idx_agent_execution_batch_status (status, updated_at)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='统一任务与训练预测批次关联历史';
