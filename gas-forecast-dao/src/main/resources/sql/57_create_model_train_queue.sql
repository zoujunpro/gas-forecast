use gas_data;

create table if not exists model_train_plan_tb (
    id bigint unsigned not null auto_increment,
    plan_no varchar(64) not null,
    agent_code varchar(64) not null,
    trigger_source varchar(32) not null,
    status varchar(32) not null,
    total_count int not null default 0,
    waiting_count int not null default 0,
    running_count int not null default 0,
    success_count int not null default 0,
    failed_count int not null default 0,
    created_by varchar(64) default null,
    created_by_name varchar(128) default null,
    created_at datetime not null default current_timestamp,
    started_at datetime default null,
    finished_at datetime default null,
    updated_at datetime not null default current_timestamp on update current_timestamp,
    primary key (id),
    unique key uk_train_plan_no (plan_no),
    key idx_train_plan_status (status, updated_at)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='模型训练计划';

create table if not exists model_train_task_tb (
    id bigint unsigned not null auto_increment,
    plan_id bigint unsigned not null,
    task_no varchar(64) not null,
    active_dedup_key varchar(512) default null comment '活动任务防重键，结束后置空',
    agent_code varchar(64) not null,
    model_id bigint unsigned not null,
    train_config_id bigint unsigned not null,
    trigger_source varchar(32) not null,
    priority int not null default 50,
    status varchar(32) not null,
    retry_count int not null default 0,
    max_retry_count int not null default 3,
    next_retry_time datetime default null,
    claimed_by varchar(128) default null,
    claimed_at datetime default null,
    retry_batch_no varchar(64) default null,
    train_batch_no varchar(64) default null,
    error_message varchar(1000) default null,
    created_at datetime not null default current_timestamp,
    started_at datetime default null,
    finished_at datetime default null,
    updated_at datetime not null default current_timestamp on update current_timestamp,
    primary key (id),
    unique key uk_train_task_no (task_no),
    unique key uk_train_task_active_dedup (active_dedup_key),
    key idx_train_task_dispatch (status, next_retry_time, priority, id),
    key idx_train_task_plan (plan_id, status),
    key idx_train_task_batch (train_batch_no)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='模型训练任务队列';
