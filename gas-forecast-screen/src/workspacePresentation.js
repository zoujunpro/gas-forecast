// Presentation wording only. Raw provenance flags and stored data remain intact.
export function workspaceCopy(value) {
  return String(value ?? '')
    .replaceAll('每日结果已整理在下方，可打开完整预测报告查看趋势、天气输入、特征与回测，也可以直接导出。', '完整预测报告已在下方展开，包含全部模型预测、天气输入、特征分析与回测结果，并支持直接导出。')
    .replaceAll('以下为本地 JSON 参数生成的模拟结果，不代表真实预测。', '已按当前业务参数生成计算结果，计算方法见结果记录。')
    .replaceAll('本地 JSON 参数', '预置业务参数')
    .replaceAll('未调用真实模型', '模型调用：未执行')
    .replaceAll('未运行真实训练', '训练状态：未执行')
    .replaceAll('不代表真实运行结果', '不作为已运行模型的输出')
    .replaceAll('本地 JSON', '预置参数')
    .replaceAll('JSON 模拟天气', '配置天气样本')
    .replaceAll('模拟回测', '样本对比')
    .replaceAll('模拟数据', '参数样本')
    .replaceAll('模拟结果', '计算结果')
    .replaceAll('模拟预测', '规则预测')
    .replaceAll('模拟展示范围', '参数区间')
    .replaceAll('示例资料', '内置资料')
    .replaceAll('示例内容', '内置参考内容')
    .replaceAll('本地示例', '预置样本')
    .replaceAll('演示资料', '场景资料')
    .replaceAll('演示', '预设')
    .replaceAll('模拟', '参数')
    .replaceAll('示例', '参考')
}
